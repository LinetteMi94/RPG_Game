    public override void Attack(Hero target, int? damage = null)
    {
        var realDamage = damage ?? Damage;
        if (!IsAlive) return;
        target.TakeDamage(realDamage, true);
        Messages.ShowDamageMessage();
        Console.WriteLine($"{Name} наносит {realDamage} урона {target.Name}!");
        Console.WriteLine($"{target.Name}, здоровье {target.Health}/{target.MaxHealth}!\n");
    }
